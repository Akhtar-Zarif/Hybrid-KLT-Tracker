%% loadMissionConfig.m
% Helper script to inspect or export mission parameter profiles for HybridKLTAutomation
% Developed by Zarif Bin Akhtar

function cfg = loadMissionConfig(profileName)
    if nargin < 1
        profileName = 'Small / High-Altitude UAV';
    end
    
    tracker = HybridKLTAutomation();
    tracker.applyMissionPreset(profileName);
    
    cfg = struct(...
        'MissionProfile', tracker.MissionProfile, ...
        'minBlobArea', tracker.minBlobArea, ...
        'filterSize', tracker.filterSize, ...
        'second_filterSize', tracker.second_filterSize, ...
        'MaxAssociationDist', tracker.MaxAssociationDist, ...
        'NumPyramidLevels', tracker.NumPyramidLevels, ...
        'MaxBidirectionalError', tracker.MaxBidirectionalError, ...
        'BlockSize', tracker.BlockSize, ...
        'MinFeatureQuality', tracker.MinFeatureQuality, ...
        'Qk', tracker.Qk, ...
        'Rk', tracker.Rk);
end
